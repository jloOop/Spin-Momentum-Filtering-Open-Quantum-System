def remove_stale_case_files(stage_dir: Path, case_prefix: str) -> List[str]:
    """Remove replaceable same-prefix outputs for a transactional rerun."""
    removed: List[str] = []
    for path in sorted(stage_dir.glob(f"{case_prefix}_*")):
        if path.is_file() or path.is_symlink():
            removed.append(path.name)
            path.unlink()
        elif path.is_dir():
            removed.append(path.name + "/")
            shutil.rmtree(path)
    return removed


def backup_existing_case_files(
    stage_dir: Path,
    case_prefix: str,
) -> Tuple[Path, List[str]]:
    """Move existing same-prefix products to a private rollback directory.

    The move itself is transactional: if any individual ``os.replace`` fails,
    every product already moved into the rollback directory is restored before
    the exception is propagated.
    """
    backup = Path(
        tempfile.mkdtemp(prefix=f".{case_prefix}_rollback_", dir=stage_dir)
    )
    moved: List[str] = []
    moved_destinations: List[Path] = []
    try:
        for path in sorted(stage_dir.glob(f"{case_prefix}_*")):
            destination = backup / path.name
            os.replace(path, destination)
            moved_destinations.append(destination)
            moved.append(path.name + ("/" if destination.is_dir() else ""))
        return backup, moved
    except Exception:
        for destination in reversed(moved_destinations):
            if destination.exists() or destination.is_symlink():
                os.replace(destination, stage_dir / destination.name)
        shutil.rmtree(backup, ignore_errors=True)
        raise


def restore_case_backup(
    stage_dir: Path,
    case_prefix: str,
    backup: Optional[Path],
) -> None:
    """Remove partial replacement products and restore the previous case."""
    remove_stale_case_files(stage_dir, case_prefix)
    if backup is not None and backup.is_dir():
        for path in sorted(backup.iterdir()):
            os.replace(path, stage_dir / path.name)
        backup.rmdir()


def discard_case_backup(backup: Optional[Path]) -> None:
    if backup is not None:
        shutil.rmtree(backup, ignore_errors=True)


