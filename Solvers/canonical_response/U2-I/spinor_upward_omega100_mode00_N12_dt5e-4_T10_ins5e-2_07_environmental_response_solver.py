def true_relative_residual(
    backend: NumericalBackend,
    matrix: Any,
    solution: Any,
    rhs: Any,
) -> float:
    residual = matrix @ solution - rhs
    numerator = backend.norm(residual)
    denominator = backend.norm(rhs)
    return numerator if denominator == 0.0 else numerator / denominator


def norm2_state(backend: NumericalBackend, state: Any, h_z: float) -> float:
    return h_z * backend.abs2_sum(state)


def lightweight_source_diagnostics(
    state: Any,
    *,
    backend: NumericalBackend,
    operators: OscillatorOperators,
    h_z: float,
    n_z: int,
) -> Tuple[float, float, float, float]:
    shaped = state.reshape(2, operators.m_modes, n_z)
    density = shaped.real * shaped.real + shaped.imag * shaped.imag
    mode_population = h_z * backend.xp.sum(density, axis=(0, 2), dtype=backend.float64)
    mode_population_cpu = np.asarray(backend.to_cpu(mode_population), dtype=np.float64)
    survival = float(np.sum(mode_population_cpu, dtype=np.float64))
    nx = float(np.dot(mode_population_cpu, operators.nx_diag))
    ny = float(np.dot(mode_population_cpu, operators.ny_diag))
    nx2 = float(np.dot(mode_population_cpu, operators.nx_diag ** 2))
    ny2 = float(np.dot(mode_population_cpu, operators.ny_diag ** 2))
    top = float(np.sum(mode_population_cpu[operators.shell_of_mode == int(np.max(operators.shell_of_mode))]))
    if survival <= 0.0:
        raise FloatingPointError("Reference survival became nonpositive")
    down = (nx + ny) / survival
    up = (
        float(np.dot(mode_population_cpu, operators.nx_diag + operators.ny_diag + 2.0))
        - (int(np.max(operators.shell_of_mode)) + 2.0) * top
    ) / survival
    phi = (nx2 / survival - (nx / survival) ** 2) + (ny2 / survival - (ny / survival) ** 2)
    return down, up, phi, top / survival


def advance_reference_factorized(
    state: Any,
    *,
    backend: NumericalBackend,
    propagator: PropagatorObjects,
    config: RunConfig,
    operators: OscillatorOperators,
    gmres_rtol: float,
) -> Tuple[Any, Any, float, int, float, float]:
    state_matrix = state.reshape(operators.d_channels, config.n_z)
    detector_output = backend.xp.zeros_like(state_matrix)
    maximum_residual = 0.0
    maximum_info = 0
    for channel in propagator.active_factorized_channels:
        input_channel = state_matrix[channel]
        rhs = propagator.backend_b @ input_channel
        solution, info = backend.gmres(
            propagator.backend_a,
            rhs,
            x0=input_channel,
            preconditioner=propagator.backend_preconditioner,
            rtol=gmres_rtol,
        )
        residual = true_relative_residual(backend, propagator.backend_a, solution, rhs)
        detector_output[channel] = solution
        maximum_residual = max(maximum_residual, residual)
        maximum_info = max(maximum_info, abs(info))
    q_roof = 0.5 * (state_matrix[:, -1] + detector_output[:, -1])
    p_roof = config.dt * config.kappa * backend.abs2_sum(q_roof)
    preclamp_norm = norm2_state(backend, detector_output.reshape(-1), propagator.h_z)
    bottom = detector_output[:, 0].copy()
    clamp_loss = propagator.h_z * backend.abs2_sum(bottom)
    detector_output[:, 0] = 0.0
    if propagator.transverse_phase_backend is None:
        raise RuntimeError("Factorized scalar phase missing")
    next_state = (
        propagator.transverse_phase_backend[:, None] * detector_output
    ).reshape(-1)
    return next_state, q_roof, p_roof, maximum_info, maximum_residual, clamp_loss


def advance_reference_spinor(
    state: Any,
    *,
    backend: NumericalBackend,
    propagator: PropagatorObjects,
    config: RunConfig,
    operators: OscillatorOperators,
    gmres_rtol: float,
) -> Tuple[Any, Any, float, int, float, float]:
    rhs = propagator.backend_b @ state
    solution, info = backend.gmres(
        propagator.backend_a,
        rhs,
        x0=state,
        preconditioner=propagator.backend_preconditioner,
        rtol=gmres_rtol,
    )
    residual = true_relative_residual(backend, propagator.backend_a, solution, rhs)
    before = state.reshape(operators.d_channels, config.n_z)
    raw_after = solution.reshape(operators.d_channels, config.n_z)
    q_roof = 0.5 * (before[:, -1] + raw_after[:, -1])
    p_roof = config.dt * config.kappa * backend.abs2_sum(q_roof)
    bottom = raw_after[:, 0].copy()
    clamp_loss = propagator.h_z * backend.abs2_sum(bottom)
    raw_after[:, 0] = 0.0
    return raw_after.reshape(-1), q_roof, p_roof, abs(info), residual, clamp_loss


def build_insertion_grid(config: RunConfig) -> Tuple[np.ndarray, np.ndarray]:
    """Construct the complete causal response grid, including both endpoints.

    For the production case DT=1e-3, T=10, INSERTION_DT=0.1 this is exactly
    101 state nodes and 100 response panels:

        0.0, 0.1, ..., 9.9, 10.0.

    The final node is retained for quadrature and closure but has no future
    detector interval, so only the preceding 100 nodes generate propagated
    insertion branches.
    """
    steps = list(range(0, config.num_steps + 1, config.insertion_stride_steps))
    if steps[-1] != config.num_steps:
        steps.append(config.num_steps)
    step_array = np.asarray(steps, dtype=np.int64)
    times = step_array.astype(np.float64) * config.dt
    if step_array.size < 3:
        raise ValueError("Insertion grid must contain at least three state nodes")
    if step_array[0] != 0 or step_array[-1] != config.num_steps:
        raise RuntimeError("Insertion grid does not cover the complete [0,T_FINAL] interval")
    if np.any(np.diff(step_array) <= 0):
        raise RuntimeError("Insertion grid is not strictly increasing")
    if not config.smoke_test:
        expected_nodes = config.num_steps // config.insertion_stride_steps + 1
        if step_array.size != expected_nodes:
            raise RuntimeError(
                "Production insertion grid is incomplete: "
                f"found {step_array.size} nodes, expected {expected_nodes}"
            )
        if not np.all(np.diff(step_array) == config.insertion_stride_steps):
            raise RuntimeError("Production insertion grid is not uniformly spaced")
    return step_array, times


def insertion_grid_contract(config: RunConfig) -> Dict[str, Any]:
    steps, times = build_insertion_grid(config)
    return {
        "node_count": int(steps.size),
        "panel_count": int(steps.size - 1),
        "first_step": int(steps[0]),
        "last_step": int(steps[-1]),
        "first_time": float(times[0]),
        "last_time": float(times[-1]),
        "stride_steps": int(config.insertion_stride_steps),
        "insertion_dt": float(config.insertion_dt),
        "uniform": bool(np.all(np.diff(steps) == config.insertion_stride_steps)),
        "complete_interval": bool(steps[0] == 0 and steps[-1] == config.num_steps),
        "all_declared_nodes_used": True,
    }


def _task05_case_paths(
    configuration_path: Path,
    prefix: str,
) -> Dict[str, Any]:
    stage_dir = configuration_path.parent.resolve()
    required: Dict[str, Any] = {
        "configuration": configuration_path.resolve(),
        "times": stage_dir / f"{prefix}_times.npy",
        "survival": stage_dir / f"{prefix}_survival.npy",
        "step_probability": stage_dir / f"{prefix}_step_loss_roof_midpoint.npy",
        "source": stage_dir / f"{prefix}_source_diagnostics.npz",
        "run_status": stage_dir / f"{prefix}_run_status.json",
        "output_hashes": stage_dir / f"{prefix}_output_hashes.json",
    }
    for name, candidate in required.items():
        if not isinstance(candidate, Path) or not candidate.is_file():
            raise FileNotFoundError(
                f"Task-05 reference file missing ({name}): {candidate}"
            )
    return required


def _task05_candidate_matches(
    path: Path,
    *,
    config: RunConfig,
    selected_mode: str,
) -> bool:
    """Return whether a Task-05 configuration matches the requested physics.

    The accepted Task-05 archive contains both canonical and explicitly audited
    noncanonical filename prefixes.  Physics fields, not directory spelling,
    therefore determine candidacy; the candidate's own ``case_prefix`` is used
    to locate and hash its products.
    """
    try:
        payload = read_json(path)
        actual_prefix = payload.get("case_prefix")
        return bool(
            payload.get("stage") == TASK05_STAGE_NAME
            and payload.get("zero_ambient_bath") is True
            and isinstance(actual_prefix, str)
            and bool(actual_prefix)
            and payload.get("propagator_type") == config.propagator_type
            and float(payload.get("omega")) == float(config.omega)
            and payload.get("initial_mode") == selected_mode
            and int(payload.get("N_shell")) == config.n_shell
            and np.isclose(
                float(payload.get("dt")), config.dt, rtol=0.0, atol=1.0e-15
            )
            and np.isclose(
                float(payload.get("T_final")),
                config.t_final,
                rtol=0.0,
                atol=1.0e-12,
            )
        )
    except Exception:
        return False


def task05_gmres_family(configuration: Mapping[str, Any]) -> Dict[str, Any]:
    """Validate and classify the accepted Task-05 Krylov family."""
    gmres = configuration.get("gmres")
    if not isinstance(gmres, Mapping):
        raise ValueError("Task-05 configuration has no valid gmres block")
    rtol = float(gmres.get("rtol"))
    atol = float(gmres.get("atol"))
    restart = int(gmres.get("restart"))
    maxiter = int(gmres.get("maxiter"))
    accepted_rtol = next(
        (
            value
            for value in ACCEPTED_TASK05_REFERENCE_GMRES_RTOLS
            if np.isclose(rtol, value, rtol=0.0, atol=1.0e-18)
        ),
        None,
    )
    if accepted_rtol is None:
        raise ValueError(
            "Task-05 reference uses an unaccepted GMRES rtol: "
            f"{rtol!r}; accepted families are "
            f"{ACCEPTED_TASK05_REFERENCE_GMRES_RTOLS}"
        )
    if not np.isclose(atol, GMRES_ATOL, rtol=0.0, atol=0.0):
        raise ValueError(f"Task-05 GMRES atol mismatch: {atol!r}")
    if restart != GMRES_RESTART or maxiter != GMRES_MAXITER:
        raise ValueError(
            "Task-05 GMRES restart/maxiter mismatch: "
            f"restart={restart}, maxiter={maxiter}"
        )
    return {
        "name": "baseline_rtol1e-8" if accepted_rtol == 1.0e-8 else "convergence_rtol1e-10",
        "rtol": float(accepted_rtol),
        "atol": atol,
        "restart": restart,
        "maxiter": maxiter,
        "passed": True,
    }


def _verified_task05_candidate_record(
    configuration_path: Path,
    *,
    prefix: str,
) -> Dict[str, Any]:
    paths = _task05_case_paths(configuration_path, prefix)
    manifest = verify_task05_manifest(paths)
    status = read_json(paths["run_status"])
    configuration = read_json(paths["configuration"])
    gmres_family = task05_gmres_family(configuration)
    status_passed = bool(
        status.get("status") == "completed"
        and status.get("all_solver_checks_passed") is True
    )
    passed = bool(manifest["all_hashes_match"] and status_passed and gmres_family["passed"])
    stable_hashes = {
        filename: record["actual"]
        for filename, record in manifest["files"].items()
        if isinstance(record, Mapping) and record.get("match") is True
    }
    scientific_fingerprint = sha256_json(
        {
            "configuration_sha256": configuration.get("configuration_sha256"),
            "case_prefix": prefix,
            "gmres_family": gmres_family,
            "stable_file_hashes": stable_hashes,
        }
    )
    return {
        "paths": paths,
        "manifest": manifest,
        "status_passed": status_passed,
        "passed": passed,
        "actual_case_prefix": prefix,
        "configuration": configuration,
        "gmres_family": gmres_family,
        "configuration_sha256": configuration.get("configuration_sha256"),
        "scientific_fingerprint": scientific_fingerprint,
    }


def locate_task05_case(
    config: RunConfig,
    *,
    initial_mode: Optional[str] = None,
) -> Dict[str, Any]:
    selected_mode = config.initial_mode if initial_mode is None else str(initial_mode)
    canonical_prefix = canonical_task05_prefix(
        config.propagator_type,
        config.omega,
        selected_mode,
        config.n_shell,
        config.dt,
        config.t_final,
    )
    canonical_filename = f"{canonical_prefix}_configuration.json"

    override_raw = config.task05_case_directory_overrides.get(selected_mode)
    override = None if override_raw is None else Path(override_raw).expanduser().resolve()
    root = config.task05_search_root.expanduser().resolve()

    if override is not None:
        if not override.is_dir():
            raise NotADirectoryError(
                f"Exact Task-05 directory override for mode {selected_mode} does not exist: "
                f"{override}"
            )
        exact_candidates = [override / canonical_filename]
        broad_candidates = sorted(override.glob("*_configuration.json"))
        discovery_root = override
        discovery_method = "exact_manual_case_directory_override"
    else:
        if not root.is_dir():
            raise NotADirectoryError(f"TASK05_SEARCH_ROOT does not exist: {root}")
        exact_candidates = sorted(root.rglob(canonical_filename))
        broad_candidates = []
        discovery_root = root
        discovery_method = "recursive_canonical_filename_search"

    def physically_matching(candidates: Sequence[Path]) -> List[Path]:
        return sorted(
            {
                candidate.resolve()
                for candidate in candidates
                if candidate.is_file()
                and _task05_candidate_matches(
                    candidate,
                    config=config,
                    selected_mode=selected_mode,
                )
            }
        )

    accepted = physically_matching(exact_candidates)
    if not accepted:
        if override is None:
            broad_candidates = sorted(root.rglob("*_configuration.json"))
            discovery_method = "recursive_physical_metadata_fallback"
        else:
            discovery_method = "manual_directory_physical_metadata_fallback"
        accepted = physically_matching(broad_candidates)

    if not accepted:
        raise RuntimeError(
            "No physically matching Task-05 reference configuration was found "
            f"for canonical target {canonical_filename} at/below {discovery_root}."
        )

    valid_records: List[Dict[str, Any]] = []
    rejected_records: List[Dict[str, Any]] = []
    for configuration_path in accepted:
        try:
            payload = read_json(configuration_path)
            actual_prefix = str(payload["case_prefix"])
            record = _verified_task05_candidate_record(
                configuration_path,
                prefix=actual_prefix,
            )
        except Exception as exc:
            rejected_records.append(
                {
                    "configuration": str(configuration_path),
                    "reason": f"{type(exc).__name__}: {exc}",
                }
            )
            continue
        if record["passed"]:
            valid_records.append(record)
        else:
            rejected_records.append(
                {
                    "configuration": str(configuration_path),
                    "reason": (
                        "Task-05 manifest, accepted GMRES family, or completed-PASS "
                        "run-status verification failed"
                    ),
                }
            )

    if not valid_records:
        raise RuntimeError(
            f"Task-05 candidates for {canonical_prefix} were found, but none passed "
            f"manifest, GMRES-family, and completed-run verification. "
            f"Rejected: {rejected_records}"
        )

    if len(valid_records) == 1:
        chosen = valid_records[0]
        selection_method = discovery_method
    else:
        fingerprints = {
            str(record["scientific_fingerprint"]) for record in valid_records
        }
        if len(fingerprints) != 1:
            valid_paths = [
                str(record["paths"]["configuration"]) for record in valid_records
            ]
            raise RuntimeError(
                f"Found {len(valid_records)} fully verified but non-identical Task-05 "
                f"copies for {canonical_prefix}: {valid_paths}. Set "
                f"TASK05_CASE_DIRECTORY_OVERRIDES[{selected_mode!r}] to the exact "
                "directory accepted by the final Task-06 audit."
            )
        valid_records.sort(
            key=lambda record: str(record["paths"]["configuration"])
        )
        chosen = valid_records[0]
        selection_method = "automatic_deduplication_of_byte_identical_verified_mirrors"

    equivalent_mirrors = [
        str(record["paths"]["configuration"].parent)
        for record in valid_records
        if record["scientific_fingerprint"] == chosen["scientific_fingerprint"]
    ]
    result = dict(chosen["paths"])
    result["task05_case_prefix"] = chosen["actual_case_prefix"]
    result["task05_configuration"] = chosen["configuration"]
    result["gmres_family"] = chosen["gmres_family"]
    result["selection_audit"] = {
        "method": selection_method,
        "selected_mode": selected_mode,
        "canonical_target_prefix": canonical_prefix,
        "actual_case_prefix": chosen["actual_case_prefix"],
        "canonical_prefix_match": chosen["actual_case_prefix"] == canonical_prefix,
        "chosen_stage_directory": str(chosen["paths"]["configuration"].parent),
        "scientific_fingerprint": chosen["scientific_fingerprint"],
        "gmres_family": chosen["gmres_family"],
        "equivalent_verified_mirrors": equivalent_mirrors,
        "rejected_candidates": rejected_records,
        "manual_override_used": override is not None,
    }
    return result


def verify_task05_manifest(paths: Mapping[str, Path]) -> Dict[str, Any]:
    manifest = read_json(paths["output_hashes"])
    files = manifest.get("files")
    if not isinstance(files, dict) or not files:
        raise ValueError("Task-05 output hash manifest is malformed")
    stage_dir = paths["configuration"].parent.resolve()
    results: Dict[str, Any] = {}
    all_match = True
    for filename, expected in sorted(files.items()):
        candidate = (stage_dir / filename).resolve()
        if candidate.parent != stage_dir:
            raise ValueError(f"Task-05 manifest path escapes its stage directory: {filename}")
        if not candidate.is_file():
            raise FileNotFoundError(f"Task-05 manifest file missing: {candidate}")
        actual = sha256_file(candidate)
        match = actual == expected
        results[filename] = {"expected": expected, "actual": actual, "match": match}
        all_match = all_match and match
    return {
        "manifest_sha256": sha256_file(paths["output_hashes"]),
        "files": results,
        "all_hashes_match": all_match,
    }



def upward_launch_task05_reference_applicable(config: RunConfig) -> bool:
    return bool(
        config.require_task05_reference
        and config.environment_direction == "upward"
        and config.initial_mode == "00"
        and config.n_shell == 12
        and np.isclose(config.t_final, 10.0, rtol=0.0, atol=1.0e-12)
        and (
            (
                np.isclose(config.omega, 1.0, rtol=0.0, atol=1.0e-12)
                and np.isclose(config.dt, 1.0e-3, rtol=0.0, atol=1.0e-15)
            )
            or (
                np.isclose(config.omega, 100.0, rtol=0.0, atol=1.0e-12)
                and np.isclose(config.dt, 5.0e-4, rtol=0.0, atol=1.0e-15)
            )
        )
    )


def required_task05_modes_before_propagation(config: RunConfig) -> Tuple[str, ...]:
    if not config.require_task05_reference:
        return tuple()
    if upward_launch_task05_reference_applicable(config):
        return ("00", "10", "01")
    return (config.initial_mode,)


def preflight_task05_references(config: RunConfig) -> Dict[str, Dict[str, Any]]:
    """Resolve and verify every Task-05 input before expensive propagation."""
    prepared: Dict[str, Dict[str, Any]] = {}
    for mode in required_task05_modes_before_propagation(config):
        paths = locate_task05_case(config, initial_mode=mode)
        manifest = verify_task05_manifest(paths)
        status = read_json(paths["run_status"])
        configuration = read_json(paths["configuration"])
        gmres_family = task05_gmres_family(configuration)
        if not manifest["all_hashes_match"]:
            raise RuntimeError(
                f"Task-05 preflight manifest verification failed for mode {mode}"
            )
        if not (
            status.get("status") == "completed"
            and status.get("all_solver_checks_passed") is True
        ):
            raise RuntimeError(
                f"Task-05 preflight run-status verification failed for mode {mode}: "
                f"{paths['run_status']}"
            )
        prepared[mode] = {
            "paths": paths,
            "manifest": manifest,
            "configuration": configuration,
            "gmres_family": gmres_family,
        }
    return prepared


def reference_gmres_rtol_from_preflight(
    config: RunConfig,
    preflight: Mapping[str, Mapping[str, Any]],
) -> float:
    if not config.require_task05_reference:
        return float(DEFAULT_REFERENCE_GMRES_RTOL)
    selected = preflight.get(config.initial_mode)
    if selected is None:
        raise RuntimeError(
            f"Task-05 preflight did not prepare selected mode {config.initial_mode}"
        )
    family = selected.get("gmres_family")
    if not isinstance(family, Mapping):
        raise RuntimeError("Selected Task-05 preflight record has no GMRES family")
    return float(family["rtol"])


def compare_reference_to_task05(
    config: RunConfig,
    reference: ReferenceProducts,
    *,
    prelocated_paths: Optional[Mapping[str, Any]] = None,
    preverified_manifest: Optional[Mapping[str, Any]] = None,
) -> Dict[str, Any]:
    if not config.require_task05_reference:
        return {
            "required": False,
            "passed": True,
            "reason": "Reduced smoke/benchmark mode does not require cluster Task-05 products.",
        }
    paths = (
        dict(prelocated_paths)
        if prelocated_paths is not None
        else locate_task05_case(config)
    )
    manifest = (
        dict(preverified_manifest)
        if preverified_manifest is not None
        else verify_task05_manifest(paths)
    )
    times = np.load(paths["times"], allow_pickle=False)
    survival = np.load(paths["survival"], allow_pickle=False)
    step_probability = np.load(paths["step_probability"], allow_pickle=False)
    with np.load(paths["source"], allow_pickle=False) as archive:
        task_down = np.asarray(archive["s_down_normalized"], dtype=np.float64)
        task_up = np.asarray(archive["s_up_normalized"], dtype=np.float64)
        task_phi = np.asarray(archive["s_phi_normalized"], dtype=np.float64)
    comparisons = {
        "times_max_abs": dense_max_abs(np.asarray(times) - reference.times) if np.asarray(times).shape == reference.times.shape else None,
        "survival_max_abs": dense_max_abs(np.asarray(survival) - reference.survival) if np.asarray(survival).shape == reference.survival.shape else None,
        "step_probability_max_abs": dense_max_abs(np.asarray(step_probability) - reference.step_probability) if np.asarray(step_probability).shape == reference.step_probability.shape else None,
        "s_down_max_abs": dense_max_abs(task_down - reference.source_down) if task_down.shape == reference.source_down.shape else None,
        "s_up_max_abs": dense_max_abs(task_up - reference.source_up) if task_up.shape == reference.source_up.shape else None,
        "s_phi_max_abs": dense_max_abs(task_phi - reference.source_phi) if task_phi.shape == reference.source_phi.shape else None,
    }
    shapes_match = bool(
        np.asarray(times).shape == reference.times.shape
        and np.asarray(survival).shape == reference.survival.shape
        and np.asarray(step_probability).shape == reference.step_probability.shape
        and task_down.shape == reference.source_down.shape
        and task_up.shape == reference.source_up.shape
        and task_phi.shape == reference.source_phi.shape
    )
    array_pass = bool(
        shapes_match
        and comparisons["times_max_abs"] is not None
        and comparisons["times_max_abs"] <= 2.0e-12
        and comparisons["survival_max_abs"] <= REFERENCE_ARRAY_ABS_TOL
        and comparisons["step_probability_max_abs"] <= REFERENCE_ARRAY_ABS_TOL
        and comparisons["s_down_max_abs"] <= REFERENCE_SOURCE_ABS_TOL
        and comparisons["s_up_max_abs"] <= REFERENCE_SOURCE_ABS_TOL
        and comparisons["s_phi_max_abs"] <= REFERENCE_SOURCE_ABS_TOL
    )
    status = read_json(paths["run_status"])
    passed = bool(
        manifest["all_hashes_match"]
        and status.get("status") == "completed"
        and status.get("all_solver_checks_passed") is True
        and array_pass
    )
    return {
        "required": True,
        "task05_canonical_target_prefix": config.task05_prefix,
        "task05_case_prefix": paths.get("task05_case_prefix", config.task05_prefix),
        "task05_stage_directory": str(paths["configuration"].parent),
        "task05_gmres_family": paths.get("gmres_family"),
        "task05_selection_audit": paths.get("selection_audit"),
        "task05_configuration_sha256": read_json(paths["configuration"]).get("configuration_sha256"),
        "task05_output_manifest": manifest,
        "shape_match": shapes_match,
        "comparison_metrics": comparisons,
        "tolerances": {
            "reference_array_abs": REFERENCE_ARRAY_ABS_TOL,
            "reference_source_abs": REFERENCE_SOURCE_ABS_TOL,
        },
        "passed": passed,
    }



def compare_reference_products(
    task05_reference: ReferenceProducts,
    response_reference: ReferenceProducts,
    *,
    task05_rtol: float,
    response_rtol: float,
) -> Dict[str, Any]:
    """Compare the regression and response zero-rate trajectories.

    This is not the exact Task-05 recovery gate.  The latter is evaluated only
    on ``task05_reference``.  This comparison verifies that tightening the
    linear solves did not select a different physical discretization or
    trajectory family before ``response_reference`` is used in the tangent
    kernel.
    """

    named_arrays = {
        "times": (task05_reference.times, response_reference.times),
        "survival": (task05_reference.survival, response_reference.survival),
        "step_probability": (
            task05_reference.step_probability,
            response_reference.step_probability,
        ),
        "source_down": (task05_reference.source_down, response_reference.source_down),
        "source_up": (task05_reference.source_up, response_reference.source_up),
        "source_phi": (task05_reference.source_phi, response_reference.source_phi),
        "top_shell": (task05_reference.top_shell, response_reference.top_shell),
    }
    shape_match = all(
        np.asarray(left).shape == np.asarray(right).shape
        for left, right in named_arrays.values()
    )
    maximum_abs = {
        name: (
            dense_max_abs(np.asarray(left) - np.asarray(right))
            if np.asarray(left).shape == np.asarray(right).shape
            else None
        )
        for name, (left, right) in named_arrays.items()
    }
    if shape_match:
        complete_law_distance = 0.5 * (
            float(
                np.sum(
                    np.abs(
                        task05_reference.step_probability
                        - response_reference.step_probability
                    ),
                    dtype=np.float64,
                )
            )
            + abs(
                float(
                    task05_reference.survival[-1]
                    - response_reference.survival[-1]
                )
            )
        )
        survival_w1 = float(
            np.trapezoid(
                np.abs(task05_reference.survival - response_reference.survival),
                task05_reference.times,
            )
        )
        detected_fraction_difference = abs(
            float(
                np.sum(task05_reference.step_probability, dtype=np.float64)
                - np.sum(response_reference.step_probability, dtype=np.float64)
            )
        )
    else:
        complete_law_distance = float("inf")
        survival_w1 = float("inf")
        detected_fraction_difference = float("inf")

    maximum_source_difference = max(
        float(maximum_abs[name])
        for name in ("source_down", "source_up", "source_phi", "top_shell")
        if maximum_abs[name] is not None
    ) if shape_match else float("inf")

    def phase_aligned_relative(left: np.ndarray, right: np.ndarray) -> float:
        left_array = np.asarray(left, dtype=np.complex128)
        right_array = np.asarray(right, dtype=np.complex128)
        left_norm = float(np.linalg.norm(left_array))
        right_norm = float(np.linalg.norm(right_array))
        scale = max(left_norm, right_norm, np.finfo(float).tiny)
        overlap = np.vdot(left_array, right_array)
        if abs(overlap) > np.finfo(float).tiny:
            right_array = right_array * np.conj(overlap / abs(overlap))
        return float(np.linalg.norm(left_array - right_array) / scale)

    if shape_match:
        node_count = int(task05_reference.insertion_steps.size)
        complex_bytes = np.dtype(np.complex128).itemsize
        task05_state_bytes = Path(
            task05_reference.selected_state_memmap_path
        ).stat().st_size
        response_state_bytes = Path(
            response_reference.selected_state_memmap_path
        ).stat().st_size
        state_denominator = complex_bytes * node_count
        if (
            task05_state_bytes != response_state_bytes
            or task05_state_bytes % state_denominator != 0
        ):
            selected_state_relative_maximum = float("inf")
            selected_state_worst_time = None
        else:
            state_dimension = task05_state_bytes // state_denominator
            task05_states = np.memmap(
                task05_reference.selected_state_memmap_path,
                mode="r",
                dtype=np.complex128,
                shape=(node_count, state_dimension),
            )
            response_states = np.memmap(
                response_reference.selected_state_memmap_path,
                mode="r",
                dtype=np.complex128,
                shape=(node_count, state_dimension),
            )
            state_relative = np.asarray(
                [
                    phase_aligned_relative(task05_states[index], response_states[index])
                    for index in range(node_count)
                ],
                dtype=np.float64,
            )
            state_worst_index = int(np.argmax(state_relative))
            selected_state_relative_maximum = float(state_relative[state_worst_index])
            selected_state_worst_time = float(
                task05_reference.insertion_times[state_worst_index]
            )

        fine_steps = int(task05_reference.step_probability.size)
        task05_q_bytes = Path(task05_reference.q_roof_memmap_path).stat().st_size
        response_q_bytes = Path(response_reference.q_roof_memmap_path).stat().st_size
        q_denominator = complex_bytes * max(fine_steps, 1)
        if (
            fine_steps == 0
            or task05_q_bytes != response_q_bytes
            or task05_q_bytes % q_denominator != 0
        ):
            q_roof_relative_maximum = float("inf")
            q_roof_worst_step = None
        else:
            q_columns = task05_q_bytes // q_denominator
            task05_q = np.memmap(
                task05_reference.q_roof_memmap_path,
                mode="r",
                dtype=np.complex128,
                shape=(fine_steps, q_columns),
            )
            response_q = np.memmap(
                response_reference.q_roof_memmap_path,
                mode="r",
                dtype=np.complex128,
                shape=(fine_steps, q_columns),
            )
            q_relative = np.asarray(
                [
                    phase_aligned_relative(task05_q[index], response_q[index])
                    for index in range(fine_steps)
                ],
                dtype=np.float64,
            )
            q_worst_index = int(np.argmax(q_relative))
            q_roof_relative_maximum = float(q_relative[q_worst_index])
            q_roof_worst_step = q_worst_index
    else:
        selected_state_relative_maximum = float("inf")
        selected_state_worst_time = None
        q_roof_relative_maximum = float("inf")
        q_roof_worst_step = None

    matched_tolerance = bool(
        np.isclose(task05_rtol, response_rtol, rtol=0.0, atol=1.0e-18)
    )
    passed = bool(
        shape_match
        and task05_reference.reference_audit.get("local_numerical_passed") is True
        and response_reference.reference_audit.get("local_numerical_passed") is True
        and complete_law_distance <= REFERENCE_CROSS_FAMILY_COMPLETE_LAW_TOL
        and float(maximum_abs["survival"]) <= REFERENCE_CROSS_FAMILY_SURVIVAL_ABS_TOL
        and maximum_source_difference <= REFERENCE_CROSS_FAMILY_SOURCE_ABS_TOL
        and selected_state_relative_maximum
        <= REFERENCE_CROSS_FAMILY_SELECTED_STATE_REL_TOL
        and q_roof_relative_maximum <= REFERENCE_CROSS_FAMILY_Q_ROOF_REL_TOL
    )
    return {
        "architecture": "dual_zero_rate_reference",
        "task05_regression_reference_rtol": float(task05_rtol),
        "response_reference_rtol": float(response_rtol),
        "same_tolerance_and_trajectory_reused": matched_tolerance,
        "shape_match": shape_match,
        "maximum_absolute_differences": maximum_abs,
        "complete_censored_law_total_variation_distance": complete_law_distance,
        "survival_W1_distance": survival_w1,
        "detected_fraction_absolute_difference": detected_fraction_difference,
        "maximum_source_diagnostic_difference": maximum_source_difference,
        "maximum_phase_aligned_selected_state_relative_difference": (
            selected_state_relative_maximum
        ),
        "worst_selected_state_time": selected_state_worst_time,
        "maximum_phase_aligned_q_roof_relative_difference": q_roof_relative_maximum,
        "worst_q_roof_fine_step": q_roof_worst_step,
        "tolerances": {
            "complete_law_total_variation": REFERENCE_CROSS_FAMILY_COMPLETE_LAW_TOL,
            "survival_Linf": REFERENCE_CROSS_FAMILY_SURVIVAL_ABS_TOL,
            "source_diagnostic_Linf": REFERENCE_CROSS_FAMILY_SOURCE_ABS_TOL,
            "phase_aligned_selected_state_relative": (
                REFERENCE_CROSS_FAMILY_SELECTED_STATE_REL_TOL
            ),
            "phase_aligned_q_roof_relative": REFERENCE_CROSS_FAMILY_Q_ROOF_REL_TOL,
        },
        "passed": passed,
        "interpretation": (
            "The Task-05 regression trajectory certifies exact archived-array "
            "recovery. The response trajectory is the numerically matched "
            "zero-rate state used by every Task-07 branch and closure identity."
        ),
    }


def propagate_zero_rate_reference(
    config: RunConfig,
    operators: OscillatorOperators,
    backend: NumericalBackend,
    propagator: PropagatorObjects,
    initial_state_cpu: np.ndarray,
    temporary_directory: Path,
    *,
    gmres_rtol: float,
    progress_label: str = "reference",
) -> ReferenceProducts:
    insertion_steps, insertion_times = build_insertion_grid(config)
    state_dimension = operators.d_channels * config.n_z
    selected_path = temporary_directory / "selected_reference_states.tmp.dat"
    q_path = temporary_directory / "reference_q_roof.tmp.dat"
    selected = np.memmap(
        selected_path,
        mode="w+",
        dtype=np.complex128,
        shape=(insertion_steps.size, state_dimension),
    )
    q_roof = np.memmap(
        q_path,
        mode="w+",
        dtype=np.complex128,
        shape=(config.num_steps, operators.d_channels),
    )
    step_to_insertion = {int(step): index for index, step in enumerate(insertion_steps)}

    times = np.arange(config.num_steps + 1, dtype=np.float64) * config.dt
    survival = np.zeros(config.num_steps + 1, dtype=np.float64)
    step_probability = np.zeros(config.num_steps, dtype=np.float64)
    true_residuals = np.zeros(config.num_steps, dtype=np.float64)
    gmres_info = np.zeros(config.num_steps, dtype=np.int32)
    source_down = np.zeros(config.num_steps + 1, dtype=np.float64)
    source_up = np.zeros(config.num_steps + 1, dtype=np.float64)
    source_phi = np.zeros(config.num_steps + 1, dtype=np.float64)
    top_shell = np.zeros(config.num_steps + 1, dtype=np.float64)
    clamp_loss = np.zeros(config.num_steps, dtype=np.float64)
    step_total = np.zeros(config.num_steps, dtype=np.float64)

    state = backend.to_backend_array(initial_state_cpu)
    survival[0] = norm2_state(backend, state, propagator.h_z)
    source_down[0], source_up[0], source_phi[0], top_shell[0] = lightweight_source_diagnostics(
        state,
        backend=backend,
        operators=operators,
        h_z=propagator.h_z,
        n_z=config.n_z,
    )
    selected[step_to_insertion[0], :] = initial_state_cpu
    current_survival = survival[0]
    maximum_info = 0
    reference_start = time.perf_counter()
    print(
        f"[{progress_label}] starting {config.num_steps} zero-rate detector steps "
        f"at GMRES rtol={gmres_rtol:.1e}",
        flush=True,
    )

    for n in range(config.num_steps):
        if config.propagator_type == "scalar_factorized":
            next_state, q_backend, p_roof, info, residual, p_clamp = advance_reference_factorized(
                state,
                backend=backend,
                propagator=propagator,
                config=config,
                operators=operators,
                gmres_rtol=gmres_rtol,
            )
        else:
            next_state, q_backend, p_roof, info, residual, p_clamp = advance_reference_spinor(
                state,
                backend=backend,
                propagator=propagator,
                config=config,
                operators=operators,
                gmres_rtol=gmres_rtol,
            )
        q_roof[n, :] = np.asarray(backend.to_cpu(q_backend), dtype=np.complex128)
        step_probability[n] = p_roof
        true_residuals[n] = residual
        gmres_info[n] = info
        clamp_loss[n] = p_clamp
        maximum_info = max(maximum_info, abs(int(info)))
        next_survival = norm2_state(backend, next_state, propagator.h_z)
        survival[n + 1] = next_survival
        step_total[n] = current_survival - next_survival
        source_down[n + 1], source_up[n + 1], source_phi[n + 1], top_shell[n + 1] = lightweight_source_diagnostics(
            next_state,
            backend=backend,
            operators=operators,
            h_z=propagator.h_z,
            n_z=config.n_z,
        )
        step = n + 1
        if step in step_to_insertion:
            selected[step_to_insertion[step], :] = np.asarray(
                backend.to_cpu(next_state), dtype=np.complex128
            )
        state = next_state
        current_survival = next_survival

        completed = n + 1
        if completed % config.progress_every == 0 or completed == config.num_steps:
            elapsed_seconds = time.perf_counter() - reference_start
            steps_per_second = completed / max(elapsed_seconds, 1.0e-15)
            remaining_seconds = (
                config.num_steps - completed
            ) / max(steps_per_second, 1.0e-15)
            print(
                f"[{progress_label}] step {completed}/{config.num_steps} "
                f"| t={completed * config.dt:.6f} "
                f"| elapsed={elapsed_seconds / 60.0:.2f} min "
                f"| rate={steps_per_second:.2f} step/s "
                f"| ETA={remaining_seconds / 60.0:.2f} min",
                flush=True,
            )

    selected.flush()
    q_roof.flush()
    click_density = step_probability / config.dt
    closure = float(survival[-1] + np.sum(step_probability, dtype=np.float64) - survival[0])
    detected = float(np.sum(step_probability, dtype=np.float64))
    closure_relative = abs(closure) / max(detected, abs(survival[0] - survival[-1]), 1.0e-15)
    flux_residual = step_total - step_probability - clamp_loss
    reference_audit = {
        "initial_survival": float(survival[0]),
        "final_survival": float(survival[-1]),
        "cumulative_midpoint_roof_probability": detected,
        "roof_probability_closure_residual": closure,
        "roof_probability_closure_relative": closure_relative,
        "maximum_true_relative_residual": float(np.max(true_residuals)),
        "maximum_gmres_info_abs": int(maximum_info),
        "maximum_survival_increase": float(max(0.0, np.max(np.diff(survival), initial=-np.inf))),
        "minimum_midpoint_probability": float(np.min(step_probability)),
        "cumulative_bottom_clamp_loss": float(np.sum(clamp_loss, dtype=np.float64)),
        "maximum_absolute_step_flux_residual": float(np.max(np.abs(flux_residual))),
        "gmres_rtol_used": float(gmres_rtol),
        "all_arrays_finite": bool(
            all(np.all(np.isfinite(array)) for array in (
                times, survival, step_probability, click_density, true_residuals,
                source_down, source_up, source_phi, top_shell,
            ))
        ),
    }
    closure_tolerance = (
        5.0e-8
        if config.smoke_test
        else max(
            ROOF_CLOSURE_ABS_TOL,
            ROOF_CLOSURE_REL_TOL * max(detected, abs(survival[0] - survival[-1])),
        )
    )
    reference_audit["closure_tolerance_used"] = closure_tolerance
    reference_audit["local_numerical_passed"] = bool(
        reference_audit["all_arrays_finite"]
        and maximum_info == 0
        and reference_audit["maximum_true_relative_residual"] <= REFERENCE_TRUE_RESIDUAL_TOL
        and reference_audit["minimum_midpoint_probability"] >= -OPERATOR_TOL
        and reference_audit["maximum_survival_increase"] <= SURVIVAL_INCREASE_TOL
        and abs(closure) <= closure_tolerance
    )
    return ReferenceProducts(
        times=times,
        survival=survival,
        step_probability=step_probability,
        click_density=click_density,
        source_down=source_down,
        source_up=source_up,
        source_phi=source_phi,
        top_shell=top_shell,
        true_residual=true_residuals,
        gmres_info=gmres_info,
        insertion_steps=insertion_steps,
        insertion_times=insertion_times,
        selected_state_memmap_path=selected_path,
        q_roof_memmap_path=q_path,
        reference_audit=reference_audit,
    )


def upward_launch_static_coefficient_audit(
    config: RunConfig,
    kernel: KernelProducts,
    *,
    preflight_references: Optional[Mapping[str, Mapping[str, Any]]] = None,
) -> Dict[str, Any]:
    """Check the exact upward launch identity against Task-05 mode laws.

    For a transverse ground-state launch,

        B_up[rho_00] = rho_10 + rho_01 - 2 rho_00.

    Therefore the *unweighted* causal click kernel at insertion time s=0
    equals the Task-05 first-shell static contrast panel by panel.  This is a
    stronger test than comparing one integrated response coefficient.
    """
    baseline_applicable = upward_launch_task05_reference_applicable(config)
    if not baseline_applicable:
        return {
            "applicable": False,
            "passed": True,
            "reason": (
                "Exact Task-05 first-shell comparison is required only for the "
                "baseline upward ground-state cases."
            ),
        }

    step_probabilities: Dict[str, np.ndarray] = {}
    provenance: Dict[str, Any] = {}
    all_inputs_pass = True
    for mode in ("00", "10", "01"):
        prepared = (
            preflight_references.get(mode)
            if preflight_references is not None
            else None
        )
        if prepared is not None:
            paths = dict(prepared["paths"])
            manifest = dict(prepared["manifest"])
        else:
            paths = locate_task05_case(config, initial_mode=mode)
            manifest = verify_task05_manifest(paths)
        status = read_json(paths["run_status"])
        probability = np.asarray(
            np.load(paths["step_probability"], allow_pickle=False),
            dtype=np.float64,
        )
        expected_shape = (config.num_steps,)
        input_pass = bool(
            manifest["all_hashes_match"]
            and status.get("status") == "completed"
            and status.get("all_solver_checks_passed") is True
            and probability.shape == expected_shape
            and np.all(np.isfinite(probability))
        )
        all_inputs_pass = all_inputs_pass and input_pass
        step_probabilities[mode] = probability
        provenance[mode] = {
            "case_prefix": canonical_task05_prefix(
                config.propagator_type,
                config.omega,
                mode,
                config.n_shell,
                config.dt,
                config.t_final,
            ),
            "stage_directory": str(paths["configuration"].parent),
            "selection_audit": paths.get("selection_audit"),
            "configuration_sha256": read_json(paths["configuration"]).get(
                "configuration_sha256"
            ),
            "output_manifest_sha256": manifest["manifest_sha256"],
            "input_passed": input_pass,
        }

    fine_contrast = (
        step_probabilities["10"]
        + step_probabilities["01"]
        - 2.0 * step_probabilities["00"]
    )
    panel_contrast = np.zeros(kernel.insertion_times.size - 1, dtype=np.float64)
    for panel in range(panel_contrast.size):
        left = int(kernel.insertion_steps[panel])
        right = int(kernel.insertion_steps[panel + 1])
        panel_contrast[panel] = float(
            np.sum(fine_contrast[left:right], dtype=np.float64)
        )
    observed = np.asarray(kernel.kernel_total_probability[:, 0], dtype=np.float64)
    if observed.shape != panel_contrast.shape:
        raise ValueError("Upward launch kernel and Task-05 panel contrast shapes differ")
    difference = observed - panel_contrast
    maximum_abs = dense_max_abs(difference)
    l1 = float(np.sum(np.abs(difference), dtype=np.float64))
    scale = max(
        dense_max_abs(observed),
        dense_max_abs(panel_contrast),
        UPWARD_STATIC_KERNEL_ABS_TOL,
    )
    relative = maximum_abs / scale
    passed = bool(
        all_inputs_pass
        and (
            maximum_abs <= UPWARD_STATIC_KERNEL_ABS_TOL
            or relative <= UPWARD_STATIC_KERNEL_REL_TOL
        )
    )
    return {
        "applicable": True,
        "identity": (
            "K_up(panel,s=0) = p_10(panel) + p_01(panel) - 2 p_00(panel)"
        ),
        "Task05_inputs": provenance,
        "maximum_abs_panel_difference": maximum_abs,
        "L1_panel_difference": l1,
        "relative_Linf_difference": relative,
        "observed_integrated_launch_kernel": float(
            np.sum(observed, dtype=np.float64)
        ),
        "Task05_integrated_first_shell_contrast": float(
            np.sum(panel_contrast, dtype=np.float64)
        ),
        "absolute_tolerance": UPWARD_STATIC_KERNEL_ABS_TOL,
        "relative_tolerance": UPWARD_STATIC_KERNEL_REL_TOL,
        "passed": passed,
    }


