class NumericalBackend:
    """SciPy/CuPy abstraction with Task-05 complex128 GMRES conventions."""

    def __init__(self, name: str):
        normalized = name.strip().lower()
        if normalized not in {"scipy", "cupy"}:
            raise ValueError("BACKEND must be 'scipy' or 'cupy'")
        self.name = normalized
        if normalized == "scipy":
            self.xp = np
            self.sparse = sp
            self.sparse_linalg = spla
            self.complex128 = np.complex128
            self.float64 = np.float64
            self._cp = None
        else:
            try:
                import cupy as cp
                import cupyx.scipy.sparse as cpsp
                import cupyx.scipy.sparse.linalg as cpspla
            except Exception as exc:
                raise RuntimeError(
                    "CuPy backend requested but CuPy/CUDA could not be imported. "
                    "Use BACKEND='scipy' only for reduced local tests."
                ) from exc
            self.xp = cp
            self.sparse = cpsp
            self.sparse_linalg = cpspla
            self.complex128 = cp.complex128
            self.float64 = cp.float64
            self._cp = cp

    def to_backend_array(self, array: np.ndarray) -> Any:
        if self.name == "scipy":
            return np.asarray(array, dtype=np.complex128)
        return self._cp.asarray(array, dtype=self._cp.complex128)

    def to_backend_sparse(self, matrix: sp.spmatrix) -> Any:
        csr = matrix.tocsr().astype(np.complex128)
        if self.name == "scipy":
            return csr
        cp = self._cp
        return self.sparse.csr_matrix(
            (
                cp.asarray(csr.data, dtype=cp.complex128),
                cp.asarray(csr.indices, dtype=cp.int32),
                cp.asarray(csr.indptr, dtype=cp.int32),
            ),
            shape=csr.shape,
            dtype=cp.complex128,
        )

    def to_cpu(self, array: Any) -> np.ndarray:
        if self.name == "scipy":
            return np.asarray(array)
        return self._cp.asnumpy(array)

    def scalar_float(self, value: Any) -> float:
        if self.name == "scipy":
            return float(value)
        return float(self._cp.asnumpy(value))

    def norm(self, vector: Any, axis: Optional[int] = None) -> Any:
        value = self.xp.linalg.norm(vector, axis=axis)
        return self.scalar_float(value) if axis is None else value

    def abs2_sum(self, array: Any, axis: Optional[Any] = None) -> Any:
        density = array.real * array.real + array.imag * array.imag
        value = self.xp.sum(density, axis=axis, dtype=self.float64)
        return self.scalar_float(value) if axis is None else value

    def make_diagonal_preconditioner(self, matrix: Any) -> Tuple[Any, Any]:
        inv_diag = 1.0 / matrix.diagonal()
        if self.name == "scipy":
            operator = self.sparse_linalg.LinearOperator(
                matrix.shape,
                matvec=lambda vector: inv_diag * vector,
                dtype=np.complex128,
            )
        else:
            operator = self.sparse_linalg.LinearOperator(
                shape=matrix.shape,
                matvec=lambda vector: inv_diag * vector,
            )
        return operator, inv_diag

    def gmres(
        self,
        matrix: Any,
        rhs: Any,
        *,
        x0: Any,
        preconditioner: Any,
        rtol: float,
    ) -> Tuple[Any, int]:
        solution, info = self.sparse_linalg.gmres(
            matrix,
            rhs,
            x0=x0,
            rtol=float(rtol),
            atol=GMRES_ATOL,
            restart=GMRES_RESTART,
            maxiter=GMRES_MAXITER,
            M=preconditioner,
        )
        return solution, int(info)

    def synchronize(self) -> None:
        if self.name == "cupy":
            self._cp.cuda.Stream.null.synchronize()

    def metadata(self) -> Dict[str, Any]:
        result: Dict[str, Any] = {
            "backend": self.name,
            "python": sys.version,
            "platform": platform.platform(),
            "numpy_version": np.__version__,
            "scipy_version": scipy.__version__,
        }
        if self.name == "cupy":
            cp = self._cp
            result["cupy_version"] = cp.__version__
            try:
                device_id = int(cp.cuda.runtime.getDevice())
                props = cp.cuda.runtime.getDeviceProperties(device_id)
                name = props.get("name", "unknown")
                if isinstance(name, bytes):
                    name = name.decode("utf-8", errors="replace")
                _free, total = cp.cuda.Device(device_id).mem_info
                result.update(
                    {
                        "cuda_device_id": device_id,
                        "cuda_device_name": str(name),
                        "cuda_compute_capability": [int(props.get("major", -1)), int(props.get("minor", -1))],
                        "cuda_total_memory_bytes": int(total),
                        "cuda_driver_version": int(cp.cuda.runtime.driverGetVersion()),
                        "cuda_runtime_version": int(cp.cuda.runtime.runtimeGetVersion()),
                    }
                )
            except Exception as exc:
                result["cuda_metadata_error"] = repr(exc)
        return result


def _complex_givens(xp: Any, a: Any, b: Any) -> Tuple[Any, Any]:
    abs_a = xp.abs(a)
    abs_b = xp.abs(b)
    magnitude = xp.sqrt(abs_a * abs_a + abs_b * abs_b)
    c = xp.ones_like(abs_a)
    s = xp.zeros_like(a)
    nonzero = magnitude > 0.0
    alpha = xp.ones_like(a)
    a_nonzero = abs_a > 0.0
    alpha = xp.where(a_nonzero, a / xp.where(a_nonzero, abs_a, 1.0), alpha)
    c = xp.where(nonzero, abs_a / xp.where(nonzero, magnitude, 1.0), c)
    s = xp.where(nonzero, alpha * xp.conj(b) / xp.where(nonzero, magnitude, 1.0), s)
    return c, s


def _batched_back_substitution(xp: Any, upper: Any, rhs: Any) -> Any:
    batches, dimension, _ = upper.shape
    solution = xp.zeros((batches, dimension), dtype=upper.dtype)
    for row in range(dimension - 1, -1, -1):
        value = rhs[:, row].copy()
        if row + 1 < dimension:
            value -= xp.sum(upper[:, row, row + 1 :] * solution[:, row + 1 :], axis=1)
        diagonal = upper[:, row, row]
        safe = xp.abs(diagonal) > 1.0e-30
        solution[:, row] = xp.where(safe, value / xp.where(safe, diagonal, 1.0), 0.0)
    return solution


def batched_independent_gmres(
    backend: NumericalBackend,
    matrix: Any,
    rhs: Any,
    x0: Any,
    inverse_diagonal: Any,
    *,
    check_every: int,
    rtol: float,
) -> Tuple[Any, np.ndarray, np.ndarray, int]:
    """Independent restarted GMRES solves vectorized over right-hand sides.

    The Krylov bases are independent; only sparse matrix--dense matrix products
    and small-vector reductions are batched.  The preconditioner, rtol, atol,
    restart, and maximum iteration count are the frozen Task-05 conventions.
    """

    xp = backend.xp
    if rhs.ndim == 1:
        rhs = rhs[:, None]
    if x0.ndim == 1:
        x0 = x0[:, None]
    solution = x0.copy()
    number_rhs = int(rhs.shape[1])
    rhs_norm = xp.linalg.norm(rhs, axis=0)
    tolerance = xp.maximum(GMRES_ATOL, float(rtol) * rhs_norm)
    total_iterations = 0
    # SciPy's frozen ``maxiter=1000`` counts restart cycles.  Preserve that
    # convention while reporting the actual inner iteration count here.
    maximum_total_inner_iterations = GMRES_MAXITER * GMRES_RESTART

    while total_iterations < maximum_total_inner_iterations:
        residual_full = rhs - matrix @ solution
        residual_norm = xp.linalg.norm(residual_full, axis=0)
        unconverged_cpu = np.asarray(backend.to_cpu(residual_norm > tolerance), dtype=bool)
        active_indices_cpu = np.flatnonzero(unconverged_cpu)
        if active_indices_cpu.size == 0:
            return (
                solution,
                np.zeros(number_rhs, dtype=np.int32),
                np.asarray(backend.to_cpu(
                    residual_norm / xp.where(rhs_norm > 0.0, rhs_norm, 1.0)
                ), dtype=np.float64),
                total_iterations,
            )

        active_indices = active_indices_cpu if backend.name == "scipy" else backend._cp.asarray(active_indices_cpu)
        active_rhs = rhs[:, active_indices]
        active_solution = solution[:, active_indices]
        active_tolerance = tolerance[active_indices]
        preconditioned_residual = inverse_diagonal[:, None] * (active_rhs - matrix @ active_solution)
        beta = xp.linalg.norm(preconditioned_residual, axis=0)
        safe_beta = xp.where(beta > 0.0, beta, 1.0)
        basis: List[Any] = [preconditioned_residual / safe_beta[None, :]]
        active_count = int(active_indices_cpu.size)
        hessenberg = xp.zeros(
            (active_count, GMRES_RESTART + 1, GMRES_RESTART), dtype=backend.complex128
        )
        cosines = xp.zeros((active_count, GMRES_RESTART), dtype=backend.float64)
        sines = xp.zeros((active_count, GMRES_RESTART), dtype=backend.complex128)
        transformed_rhs = xp.zeros((active_count, GMRES_RESTART + 1), dtype=backend.complex128)
        transformed_rhs[:, 0] = beta
        candidate = active_solution.copy()
        exact_residual = xp.linalg.norm(active_rhs - matrix @ candidate, axis=0)

        maximum_inner = min(
            GMRES_RESTART,
            maximum_total_inner_iterations - total_iterations,
        )
        used_inner = 0
        for k in range(maximum_inner):
            work = inverse_diagonal[:, None] * (matrix @ basis[k])
            # Modified Gram--Schmidt with one reorthogonalization pass.
            for _pass in range(2):
                for i in range(k + 1):
                    coefficient = xp.sum(xp.conj(basis[i]) * work, axis=0)
                    hessenberg[:, i, k] += coefficient
                    work -= basis[i] * coefficient[None, :]
            next_norm = xp.linalg.norm(work, axis=0)
            hessenberg[:, k + 1, k] = next_norm
            safe_next = xp.where(next_norm > 1.0e-30, next_norm, 1.0)
            basis.append(work / safe_next[None, :])

            for i in range(k):
                top = hessenberg[:, i, k].copy()
                bottom = hessenberg[:, i + 1, k].copy()
                hessenberg[:, i, k] = cosines[:, i] * top + sines[:, i] * bottom
                hessenberg[:, i + 1, k] = -xp.conj(sines[:, i]) * top + cosines[:, i] * bottom

            cosine, sine = _complex_givens(
                xp, hessenberg[:, k, k], hessenberg[:, k + 1, k]
            )
            cosines[:, k] = cosine
            sines[:, k] = sine
            top = hessenberg[:, k, k].copy()
            bottom = hessenberg[:, k + 1, k].copy()
            hessenberg[:, k, k] = cosine * top + sine * bottom
            hessenberg[:, k + 1, k] = 0.0
            rhs_top = transformed_rhs[:, k].copy()
            rhs_bottom = transformed_rhs[:, k + 1].copy()
            transformed_rhs[:, k] = cosine * rhs_top + sine * rhs_bottom
            transformed_rhs[:, k + 1] = -xp.conj(sine) * rhs_top + cosine * rhs_bottom

            used_inner = k + 1
            should_check = (
                used_inner % check_every == 0
                or used_inner == maximum_inner
                or xp.all(xp.abs(transformed_rhs[:, used_inner]) <= active_tolerance)
            )
            if bool(backend.scalar_float(should_check)):
                coefficients = _batched_back_substitution(
                    xp,
                    hessenberg[:, :used_inner, :used_inner],
                    transformed_rhs[:, :used_inner],
                )
                correction = xp.zeros_like(active_solution)
                for i in range(used_inner):
                    correction += basis[i] * coefficients[:, i][None, :]
                candidate = active_solution + correction
                exact_residual = xp.linalg.norm(active_rhs - matrix @ candidate, axis=0)
                if bool(backend.scalar_float(xp.all(exact_residual <= active_tolerance))):
                    solution[:, active_indices] = candidate
                    total_iterations += used_inner
                    residual_norm = xp.linalg.norm(rhs - matrix @ solution, axis=0)
                    return (
                        solution,
                        np.zeros(number_rhs, dtype=np.int32),
                        np.asarray(backend.to_cpu(
                            residual_norm / xp.where(rhs_norm > 0.0, rhs_norm, 1.0)
                        ), dtype=np.float64),
                        total_iterations,
                    )

        solution[:, active_indices] = candidate
        total_iterations += used_inner

    final_residual = xp.linalg.norm(rhs - matrix @ solution, axis=0)
    final_residual_cpu = np.asarray(backend.to_cpu(final_residual), dtype=np.float64)
    rhs_norm_cpu = np.asarray(backend.to_cpu(rhs_norm), dtype=np.float64)
    relative_residual_cpu = final_residual_cpu / np.where(rhs_norm_cpu > 0.0, rhs_norm_cpu, 1.0)
    tolerance_cpu = np.asarray(backend.to_cpu(tolerance), dtype=np.float64)
    info = np.where(final_residual_cpu <= tolerance_cpu, 0, total_iterations).astype(np.int32)
    return solution, info, relative_residual_cpu, total_iterations


def solve_many(
    backend: NumericalBackend,
    matrix: Any,
    rhs: Any,
    x0: Any,
    preconditioner: Any,
    inverse_diagonal: Any,
    *,
    use_batched: bool,
    check_every: int,
    rtol: float,
) -> Tuple[Any, np.ndarray, np.ndarray, int]:
    if rhs.ndim == 1:
        rhs = rhs[:, None]
    if x0.ndim == 1:
        x0 = x0[:, None]
    count = int(rhs.shape[1])
    if count == 0:
        return x0.copy(), np.empty(0, np.int32), np.empty(0, np.float64), 0
    if backend.name == "cupy" and use_batched and count > 1:
        return batched_independent_gmres(
            backend,
            matrix,
            rhs,
            x0,
            inverse_diagonal,
            check_every=check_every,
            rtol=rtol,
        )

    solutions: List[Any] = []
    infos = np.zeros(count, dtype=np.int32)
    residuals = np.zeros(count, dtype=np.float64)
    for column in range(count):
        solution, info = backend.gmres(
            matrix,
            rhs[:, column],
            x0=x0[:, column],
            preconditioner=preconditioner,
            rtol=rtol,
        )
        solutions.append(solution)
        infos[column] = info
        residual = matrix @ solution - rhs[:, column]
        numerator = backend.norm(residual)
        denominator = backend.norm(rhs[:, column])
        residuals[column] = numerator if denominator == 0.0 else numerator / denominator
    return backend.xp.stack(solutions, axis=1), infos, residuals, 0


