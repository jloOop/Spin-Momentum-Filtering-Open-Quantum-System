def advance_many_spinor(
    vectors: Any,
    *,
    backend: NumericalBackend,
    propagator: PropagatorObjects,
    config: RunConfig,
    operators: OscillatorOperators,
) -> Tuple[Any, Any, np.ndarray, np.ndarray, int]:
    rhs = propagator.backend_b @ vectors
    solution, infos, residuals, iterations = solve_many(
        backend,
        propagator.backend_a,
        rhs,
        vectors,
        propagator.backend_preconditioner,
        propagator.backend_inverse_diagonal,
        use_batched=config.use_batched_gmres,
        check_every=config.batched_gmres_check_every,
        rtol=config.branch_gmres_rtol,
    )
    before = vectors.reshape(operators.d_channels, config.n_z, -1)
    after = solution.reshape(operators.d_channels, config.n_z, -1)
    q_roof = 0.5 * (before[:, -1, :] + after[:, -1, :])
    after[:, 0, :] = 0.0
    return after.reshape(vectors.shape), q_roof, infos, residuals, iterations


def advance_many_factorized(
    vectors: Any,
    *,
    backend: NumericalBackend,
    propagator: PropagatorObjects,
    config: RunConfig,
    operators: OscillatorOperators,
) -> Tuple[Any, Any, np.ndarray, np.ndarray, int]:
    shaped = vectors.reshape(operators.d_channels, config.n_z, -1)
    columns = int(shaped.shape[2])
    # Treat each nonzero (channel, branch) pair as one longitudinal RHS.
    pair_matrix = shaped.transpose(1, 0, 2).reshape(config.n_z, -1)
    pair_norm = backend.xp.linalg.norm(pair_matrix, axis=0)
    active_cpu = np.flatnonzero(np.asarray(backend.to_cpu(pair_norm > 0.0), dtype=bool))
    detector_pairs = backend.xp.zeros_like(pair_matrix)
    infos = np.zeros(pair_matrix.shape[1], dtype=np.int32)
    residuals = np.zeros(pair_matrix.shape[1], dtype=np.float64)
    iterations = 0
    if active_cpu.size:
        active = active_cpu if backend.name == "scipy" else backend._cp.asarray(active_cpu)
        inputs = pair_matrix[:, active]
        rhs = propagator.backend_b @ inputs
        solutions, active_info, active_residual, iterations = solve_many(
            backend,
            propagator.backend_a,
            rhs,
            inputs,
            propagator.backend_preconditioner,
            propagator.backend_inverse_diagonal,
            use_batched=config.use_batched_gmres,
            check_every=config.batched_gmres_check_every,
            rtol=config.branch_gmres_rtol,
        )
        detector_pairs[:, active] = solutions
        infos[active_cpu] = active_info
        residuals[active_cpu] = active_residual
    detector = detector_pairs.reshape(config.n_z, operators.d_channels, columns).transpose(1, 0, 2)
    q_roof = 0.5 * (shaped[:, -1, :] + detector[:, -1, :])
    detector[:, 0, :] = 0.0
    if propagator.transverse_phase_backend is None:
        raise RuntimeError("Factorized scalar phase missing")
    next_vectors = propagator.transverse_phase_backend[:, None, None] * detector
    # Return one info/residual per wave-function branch.
    infos_branch = infos.reshape(operators.d_channels, columns).max(axis=0)
    residuals_branch = residuals.reshape(operators.d_channels, columns).max(axis=0)
    return next_vectors.reshape(vectors.shape), q_roof, infos_branch, residuals_branch, iterations


def advance_many_detector(
    vectors: Any,
    *,
    backend: NumericalBackend,
    propagator: PropagatorObjects,
    config: RunConfig,
    operators: OscillatorOperators,
) -> Tuple[Any, Any, np.ndarray, np.ndarray, int]:
    if config.propagator_type == "scalar_factorized":
        return advance_many_factorized(
            vectors,
            backend=backend,
            propagator=propagator,
            config=config,
            operators=operators,
        )
    return advance_many_spinor(
        vectors,
        backend=backend,
        propagator=propagator,
        config=config,
        operators=operators,
    )


def run_backend_batched_gmres_certification(
    config: RunConfig,
    backend: NumericalBackend,
) -> Dict[str, Any]:
    """Certify the production CuPy batched solve against independent CuPy GMRES.

    The certification is a reduced algebraic detector calculation.  It is
    skipped for SciPy and when batched production is disabled; in the actual
    CuPy production configuration it is a mandatory pre-propagation gate.
    """
    if backend.name != "cupy" or not config.use_batched_gmres:
        return {
            "applicable": False,
            "reason": "CuPy batched production path is not selected.",
            "passed": True,
        }

    reduced = replace(
        config,
        propagator_type="spinor",
        environment_direction="upward",
        initial_mode="00",
        omega=4.0,
        n_shell=2,
        dt=2.0e-3,
        t_final=2.0e-2,
        insertion_dt=4.0e-3,
        case_prefix="task07_cupy_batched_certification",
        n_z=32,
        l_z=4.0,
        z0=3.0,
        sigma_z_amplitude=0.35,
        smoke_test=True,
        require_task05_reference=False,
        insertion_batch_size=1,
        use_batched_gmres=True,
    )
    operators = build_oscillator_operators(reduced.n_shell, reduced.omega)
    z, h_z, _ = build_reference_grid(reduced.n_z, reduced.l_z)
    initial_cpu = build_initial_state(reduced, operators, z, h_z)
    propagator = build_propagator_objects(
        reduced,
        operators,
        backend,
        initial_cpu,
    )
    sources = source_vectors_at_state(
        initial_cpu,
        operators=operators,
        direction="upward",
        h_z=propagator.h_z,
        n_z=reduced.n_z,
    )
    vectors_cpu = np.asarray(sources["branch_vectors"], dtype=np.complex128)
    nonzero = np.linalg.norm(vectors_cpu, axis=0) > 0.0
    vectors_cpu = vectors_cpu[:, nonzero]
    if vectors_cpu.shape[1] < 2:
        raise RuntimeError("Reduced CuPy certification did not produce multiple RHS")
    vectors = backend.to_backend_array(vectors_cpu)
    rhs = propagator.backend_b @ vectors

    batched, batch_info, batch_residual, iterations = batched_independent_gmres(
        backend,
        propagator.backend_a,
        rhs,
        vectors,
        propagator.backend_inverse_diagonal,
        check_every=reduced.batched_gmres_check_every,
        rtol=reduced.branch_gmres_rtol,
    )
    independent, independent_info, independent_residual, _ = solve_many(
        backend,
        propagator.backend_a,
        rhs,
        vectors,
        propagator.backend_preconditioner,
        propagator.backend_inverse_diagonal,
        use_batched=False,
        check_every=reduced.batched_gmres_check_every,
        rtol=reduced.branch_gmres_rtol,
    )
    backend.synchronize()
    batched_cpu = np.asarray(backend.to_cpu(batched), dtype=np.complex128)
    independent_cpu = np.asarray(backend.to_cpu(independent), dtype=np.complex128)
    solution_relative = float(
        np.linalg.norm(batched_cpu - independent_cpu)
        / max(np.linalg.norm(independent_cpu), np.finfo(float).tiny)
    )

    before = vectors_cpu.reshape(operators.d_channels, reduced.n_z, -1)
    after_batched = batched_cpu.reshape(operators.d_channels, reduced.n_z, -1)
    after_independent = independent_cpu.reshape(operators.d_channels, reduced.n_z, -1)
    q_batched = 0.5 * (before[:, -1, :] + after_batched[:, -1, :])
    q_independent = 0.5 * (before[:, -1, :] + after_independent[:, -1, :])
    roof_batched = reduced.dt * reduced.kappa * np.sum(
        np.abs(q_batched) ** 2,
        axis=0,
        dtype=np.float64,
    )
    roof_independent = reduced.dt * reduced.kappa * np.sum(
        np.abs(q_independent) ** 2,
        axis=0,
        dtype=np.float64,
    )
    roof_difference = dense_max_abs(roof_batched - roof_independent)
    maximum_residual = max(
        float(np.max(batch_residual, initial=0.0)),
        float(np.max(independent_residual, initial=0.0)),
    )
    maximum_info = max(
        int(np.max(np.abs(batch_info), initial=0)),
        int(np.max(np.abs(independent_info), initial=0)),
    )
    passed = bool(
        maximum_info == 0
        and maximum_residual <= BRANCH_TRUE_RESIDUAL_TOL
        and solution_relative <= BATCHED_CERTIFICATION_SOLUTION_REL_TOL
        and roof_difference <= BATCHED_CERTIFICATION_OBSERVABLE_ABS_TOL
    )
    return {
        "applicable": True,
        "backend": backend.name,
        "reduced_configuration": {
            "N_shell": reduced.n_shell,
            "N_z": reduced.n_z,
            "dt": reduced.dt,
            "omega": reduced.omega,
            "number_rhs": int(vectors_cpu.shape[1]),
            "branch_gmres_rtol": reduced.branch_gmres_rtol,
        },
        "maximum_gmres_info_abs": maximum_info,
        "maximum_true_relative_residual": maximum_residual,
        "relative_solution_difference": solution_relative,
        "maximum_midpoint_roof_probability_difference": roof_difference,
        "custom_batched_inner_iterations": int(iterations),
        "solution_relative_tolerance": BATCHED_CERTIFICATION_SOLUTION_REL_TOL,
        "observable_absolute_tolerance": BATCHED_CERTIFICATION_OBSERVABLE_ABS_TOL,
        "passed": passed,
    }


