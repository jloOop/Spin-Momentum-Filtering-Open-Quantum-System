def _number_token(value: float) -> str:
    numeric = float(value)
    if numeric.is_integer():
        return str(int(numeric))
    mantissa, exponent = f"{numeric:.12e}".split("e")
    mantissa = mantissa.rstrip("0").rstrip(".").replace(".", "p")
    return f"{mantissa}e{int(exponent)}"


