def integrated_response_metrics(
    config: RunConfig,
    kernel: KernelProducts,
) -> Dict[str, float]:
    times = kernel.insertion_times
    chi_s = kernel.chi_survival
    chi_p = kernel.chi_panel_probability
    durations = kernel.panel_durations
    chi_g = kernel.chi_click_density
    chi_d = float(np.sum(chi_p, dtype=np.float64))
    chi_mu = float(np.trapezoid(chi_s, times))
    early = 0.0
    late = 0.0
    for panel, (left, right) in enumerate(zip(times[:-1], times[1:])):
        duration = right - left
        if right <= config.t_cut:
            early += chi_p[panel]
        elif left >= config.t_cut:
            late += chi_p[panel]
        else:
            early_fraction = (config.t_cut - left) / duration
            early += early_fraction * chi_p[panel]
            late += (1.0 - early_fraction) * chi_p[panel]
    complete_norm = 0.5 * (
        float(np.sum(np.abs(chi_p), dtype=np.float64)) + abs(float(chi_s[-1]))
    )
    return {
        "chi_D_from_panel_sum": chi_d,
        "chi_D_from_final_survival": -float(chi_s[-1]),
        "chi_mu_restricted": chi_mu,
        "chi_D_E": float(early),
        "chi_D_L": float(late),
        "chi_complete_signed_measure_norm": complete_norm,
        "chi_survival_W1_norm": float(np.trapezoid(np.abs(chi_s), times)),
        "maximum_abs_chi_survival": dense_max_abs(chi_s),
        "maximum_abs_chi_click_density": dense_max_abs(chi_g),
        "minimum_chi_click_density": float(np.min(chi_g)),
        "maximum_chi_click_density": float(np.max(chi_g)),
    }


