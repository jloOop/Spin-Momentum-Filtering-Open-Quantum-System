"""
07_environmental_response_solver.py
===================================

Task 07: standalone zero-rate environmental-response solver for the
factorized scalar and spin-coupled absorbing-boundary detectors.

This program differentiates the *implemented finite-step symmetric
bath--detector composition* at zero environmental rate.  It does not replace
that map by a different continuous-time propagator.  The detector substep is
exactly the validated Task-05 Cayley/Crank--Nicolson map with the frozen
longitudinal grid, complete-shell oscillator ordering, physical-spin ordering,
+K_N/(2 h_z) roof term, complex128 GMRES conventions, post-solve bottom
Dirichlet assignment, and midpoint roof-loss functional.

For one detector step D_h[rho] = U_h rho U_h^dagger and one unit environmental
direction B, the implemented Strang map is

    S_(epsilon,h) = exp[(epsilon h/2) B] o D_h o exp[(epsilon h/2) B].

Its exact derivative at epsilon=0 is used.  Equivalently, at detector state
nodes the discrete tangent is the trapezoidal Duhamel sum generated by the two
bath half-step derivatives.  The reference propagation itself always has zero
environmental rate.

Reference-accuracy architecture
-------------------------------
When the selected archived Task-05 case uses a different GMRES tolerance from
Task 07, two zero-rate trajectories are generated.  The first reproduces the
Task-05 arrays exactly at their archived tolerance.  The second uses the same
GMRES tolerance as every environmental branch and is the only trajectory used
inside the response kernel and tangent probability closure.  This prevents a
mixed-accuracy bilinear closure test while preserving the Task-05 regression
gate.

Two implementations are mandatory and included:

1. a deliberately reduced dense full-tangent density-matrix benchmark;
2. a production low-rank wave-function insertion method.

For every dissipator D[L], the production method retains both

    |L psi><L psi|                         (jump)

and

   -1/2 (|L^dagger L psi><psi| + h.c.)    (anticommutator).

A jump-only response is impossible in this source.

One manually selected physical response case is executed per invocation.
There is no production sweep, finite positive rate, bath temperature,
trajectory/Monte-Carlo path, explicit detector reservoir, CAP, or second roof
loss mechanism.

Response-grid convention
------------------------
The detector reference is advanced at every frozen Task-05 time step.  The
causal insertion kernel is evaluated on a separately declared state-time grid.
Every kernel entry is accumulated from the underlying fine detector steps.
Every invocation follows one complete production path.  It first verifies the
archived Task-05 trajectory, generates a numerically matched response reference,
runs a selected full-dimension closure pilot, and—only after that pilot passes—
automatically evaluates the complete declared insertion grid from zero through
the observation horizon.  For the default case this is 101 state nodes,
``0.0, 0.1, ..., 10.0``, and 100 response panels.  The selected pilot columns
are a fail-fast numerical guard; they never replace the complete kernel.  The
saved ``times.npy`` and ``insertion_times.npy`` contain the same response
state-node grid. ``chi_survival.npy`` has one value per state node;
``chi_click_density.npy`` has one panel-averaged value between consecutive
state nodes.

Exit status
-----------
0 : all solver gates required for this case role pass, including the identical-prefix rerun
3 : case-local gates pass, but rerun, family controls, or evidence resolution remains pending
2 : a completed numerical/scientific gate fails
1 : execution or I/O failure
"""

