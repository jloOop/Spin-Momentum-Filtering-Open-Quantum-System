def unique_task05_dependencies_for_frozen_task07(
    config: RunConfig,
) -> List[RunConfig]:
    """Return the deduplicated Task-05 references required by all 15 cases."""
    unique: Dict[Tuple[Any, ...], RunConfig] = {}
    for record in frozen_minimal_case_matrix(config.insertion_dt):
        physical = replace(
            config,
            propagator_type=str(record["propagator_type"]),
            environment_direction=str(record["environment_direction"]),
            initial_mode=str(record["initial_mode"]),
            omega=float(record["omega"]),
            n_shell=int(record["N_shell"]),
            dt=float(record["dt"]),
            t_final=float(record["T_final"]),
            insertion_dt=float(record["insertion_dt"]),
            case_prefix=canonical_task07_prefix(
                str(record["propagator_type"]),
                str(record["environment_direction"]),
                float(record["omega"]),
                str(record["initial_mode"]),
                int(record["N_shell"]),
                float(record["dt"]),
                float(record["T_final"]),
                float(record["insertion_dt"]),
            ),
        )
        for required_mode in required_task05_modes_before_propagation(physical):
            dependency = replace(physical, initial_mode=required_mode)
            key = (
                dependency.propagator_type,
                float(dependency.omega),
                dependency.initial_mode,
                int(dependency.n_shell),
                float(dependency.dt),
                float(dependency.t_final),
            )
            unique[key] = dependency
    return [unique[key] for key in sorted(unique, key=lambda item: tuple(map(str, item)))]


