def frozen_baseline_dt(omega: float) -> float:
    if np.isclose(float(omega), 1.0, rtol=0.0, atol=1.0e-12):
        return 1.0e-3
    if np.isclose(float(omega), 100.0, rtol=0.0, atol=1.0e-12):
        return 5.0e-4
    raise ValueError("The frozen Task-07 matrix defines baseline dt only for omega=1 and 100")


def task07_case_role(config: RunConfig) -> str:
    if config.propagator_type == "scalar_factorized":
        return "scalar_exact_null"
    if not (
        np.isclose(config.omega, 1.0, rtol=0.0, atol=1.0e-12)
        or np.isclose(config.omega, 100.0, rtol=0.0, atol=1.0e-12)
    ):
        return "additional_control"
    baseline_dt = frozen_baseline_dt(config.omega)
    if np.isclose(config.omega, 100.0, rtol=0.0, atol=1.0e-12):
        if config.n_shell == 12 and np.isclose(config.dt, baseline_dt, rtol=0.0, atol=1.0e-15):
            return "production_baseline"
        if config.n_shell == 12 and np.isclose(config.dt, baseline_dt / 2.0, rtol=0.0, atol=1.0e-15):
            return "time_step_control"
        if config.n_shell == 16 and np.isclose(config.dt, baseline_dt, rtol=0.0, atol=1.0e-15):
            return "shell_cutoff_control"
    if np.isclose(config.omega, 1.0, rtol=0.0, atol=1.0e-12):
        return "weak_confinement_control"
    return "additional_control"


def verify_task07_manifest(configuration_path: Path) -> Dict[str, Any]:
    configuration = read_json(configuration_path)
    prefix = str(configuration["case_prefix"])
    stage_dir = configuration_path.parent.resolve()
    manifest_path = stage_dir / f"{prefix}_output_hashes.json"
    status_path = stage_dir / f"{prefix}_run_status.json"
    if not manifest_path.is_file() or not status_path.is_file():
        raise FileNotFoundError(f"Task-07 control case is incomplete: {configuration_path}")
    manifest = read_json(manifest_path)
    status = read_json(status_path)
    files = manifest.get("files", {})
    if not isinstance(files, dict) or not files:
        raise ValueError(f"Malformed Task-07 output manifest: {manifest_path}")
    all_match = True
    for filename, expected in files.items():
        candidate = (stage_dir / filename).resolve()
        if candidate.parent != stage_dir:
            raise ValueError(f"Task-07 manifest path escapes its stage directory: {filename}")
        if not candidate.is_file() or sha256_file(candidate) != expected:
            all_match = False

    # This fingerprint deliberately excludes the copied source and configuration,
    # whose hashes change when only STAGE_FOLDER_NUMBER is edited.  It identifies
    # the compact scientific response products used by the family comparison.
    compact_suffixes = (
        "times.npy",
        "insertion_times.npy",
        "chi_survival.npy",
        "chi_click_density.npy",
        "kernel_summary.npz",
        "source_insertion_summary.npz",
        "integrated_response.json",
    )
    compact_hashes = {
        suffix: expected
        for filename, expected in files.items()
        for suffix in compact_suffixes
        if filename == f"{prefix}_{suffix}"
    }
    compact_fingerprint = (
        sha256_json(compact_hashes)
        if len(compact_hashes) == len(compact_suffixes)
        else None
    )
    return {
        "configuration": configuration,
        "manifest": manifest,
        "status": status,
        "all_hashes_match": all_match,
        "configuration_path": configuration_path,
        "compact_response_fingerprint": compact_fingerprint,
        "compact_response_hashes": compact_hashes,
    }


def discover_task07_response_family(config: RunConfig) -> Dict[Tuple[int, float], Dict[str, Any]]:
    """Discover response controls without making folder numbering authoritative.

    Multiple numbered folders containing byte-identical compact response data are
    treated as equivalent mirrors.  If conflicting copies exist, the currently
    selected manual stage directory wins for the current case.  Conflicting
    copies of an external control are marked invalid/pending rather than aborting
    the completed local case.
    """
    root = config.out_root.expanduser().resolve()
    groups: Dict[Tuple[int, float], List[Dict[str, Any]]] = {}
    if not root.is_dir():
        return {}
    for path in root.rglob("*_configuration.json"):
        try:
            payload = read_json(path)
        except Exception:
            continue
        if payload.get("stage") != STAGE_NAME:
            continue
        if payload.get("propagator_type") != config.propagator_type:
            continue
        if payload.get("environment_direction") != config.environment_direction:
            continue
        if payload.get("initial_mode") != config.initial_mode:
            continue
        if not np.isclose(float(payload.get("omega")), config.omega, rtol=0.0, atol=1.0e-12):
            continue
        if not np.isclose(float(payload.get("T_final")), config.t_final, rtol=0.0, atol=1.0e-12):
            continue
        if not np.isclose(float(payload.get("insertion_dt")), config.insertion_dt, rtol=0.0, atol=1.0e-12):
            continue
        key = (int(payload.get("N_shell")), round(float(payload.get("dt")), 15))
        try:
            record = verify_task07_manifest(path.resolve())
        except Exception as exc:
            record = {
                "configuration": payload,
                "configuration_path": path.resolve(),
                "error": f"{type(exc).__name__}: {exc}",
                "all_hashes_match": False,
                "status": {},
                "compact_response_fingerprint": None,
            }
        groups.setdefault(key, []).append(record)

    family: Dict[Tuple[int, float], Dict[str, Any]] = {}
    current_stage_dir = config.stage_dir.resolve()
    for key, records in groups.items():
        records.sort(key=lambda record: str(record["configuration_path"]))
        valid = [record for record in records if record.get("all_hashes_match") is True]
        current = [
            record
            for record in records
            if Path(record["configuration_path"]).parent.resolve() == current_stage_dir
        ]

        if current:
            chosen = dict(current[0])
        elif valid:
            fingerprints = {
                record.get("compact_response_fingerprint") for record in valid
            }
            fingerprints.discard(None)
            if len(fingerprints) == 1 and len(valid) == len(records):
                chosen = dict(valid[0])
            else:
                # Do not select non-identical external controls silently.  Mark
                # the control pending while allowing the current case to finish.
                chosen = dict(valid[0])
                chosen["all_hashes_match"] = False
                chosen["duplicate_conflict"] = [
                    str(record["configuration_path"]) for record in records
                ]
        else:
            chosen = dict(records[0])

        chosen["equivalent_or_discovered_mirrors"] = [
            str(record["configuration_path"]) for record in records
        ]
        family[key] = chosen
    return family

def load_compact_response_case(record: Mapping[str, Any]) -> Dict[str, np.ndarray]:
    configuration = record["configuration"]
    prefix = str(configuration["case_prefix"])
    stage_dir = Path(record["configuration_path"]).parent
    times = np.load(stage_dir / f"{prefix}_times.npy", allow_pickle=False)
    chi_s = np.load(stage_dir / f"{prefix}_chi_survival.npy", allow_pickle=False)
    with np.load(stage_dir / f"{prefix}_kernel_summary.npz", allow_pickle=False) as archive:
        chi_p = np.asarray(archive["chi_panel_probability"], dtype=np.float64)
    return {
        "times": np.asarray(times, dtype=np.float64),
        "chi_survival": np.asarray(chi_s, dtype=np.float64),
        "chi_panel_probability": chi_p,
    }


def signed_response_distance(left: Mapping[str, np.ndarray], right: Mapping[str, np.ndarray]) -> Dict[str, float]:
    if left["times"].shape != right["times"].shape or dense_max_abs(left["times"] - right["times"]) > 2.0e-12:
        raise ValueError("Task-07 control response grids differ")
    if left["chi_survival"].shape != right["chi_survival"].shape:
        raise ValueError("Task-07 control survival response shapes differ")
    if left["chi_panel_probability"].shape != right["chi_panel_probability"].shape:
        raise ValueError("Task-07 control panel-response shapes differ")
    distance = 0.5 * (
        float(np.sum(np.abs(left["chi_panel_probability"] - right["chi_panel_probability"]), dtype=np.float64))
        + abs(float(left["chi_survival"][-1] - right["chi_survival"][-1]))
    )
    left_norm = 0.5 * (
        float(np.sum(np.abs(left["chi_panel_probability"]), dtype=np.float64))
        + abs(float(left["chi_survival"][-1]))
    )
    right_norm = 0.5 * (
        float(np.sum(np.abs(right["chi_panel_probability"]), dtype=np.float64))
        + abs(float(right["chi_survival"][-1]))
    )
    return {
        "signed_measure_distance": distance,
        "relative_signed_measure_distance": distance / max(left_norm, right_norm, INSERTION_CONVERGENCE_ABS_TOL),
        "left_response_norm": left_norm,
        "right_response_norm": right_norm,
        "maximum_abs_survival_difference": dense_max_abs(left["chi_survival"] - right["chi_survival"]),
    }


def audit_external_response_controls(
    config: RunConfig,
    *,
    local_insertion_error: float,
    maximum_branch_residual: float,
    maximum_source_trace_residual: float,
    benchmark_error: float,
    current_local_pass: bool,
    current_rerun_pass: bool,
) -> Dict[str, Any]:
    role = task07_case_role(config)
    if config.propagator_type == "scalar_factorized":
        return {
            "case_role": role,
            "time_step_status": "NOT_REQUIRED_EXACT_SCALAR_NULL",
            "shell_cutoff_status": "NOT_REQUIRED_EXACT_SCALAR_NULL",
            "evidence_status": "NULL_CONTROL_NO_NONZERO_CLAIM",
            "all_required_controls_available": True,
            "all_required_controls_passed": True,
            "solver_evidence_gate_passed": True,
        }
    if not np.isclose(config.omega, 100.0, rtol=0.0, atol=1.0e-12):
        return {
            "case_role": role,
            "time_step_status": "NOT_REQUIRED_FOR_OMEGA1_CONFINEMENT_CONTROL",
            "shell_cutoff_status": "NOT_REQUIRED_FOR_OMEGA1_CONFINEMENT_CONTROL",
            "evidence_status": "NO_STANDALONE_PRODUCTION_CLAIM",
            "all_required_controls_available": True,
            "all_required_controls_passed": True,
            "solver_evidence_gate_passed": True,
        }

    baseline_dt = frozen_baseline_dt(config.omega)
    family = discover_task07_response_family(config)
    current_key = (config.n_shell, round(float(config.dt), 15))
    if current_key in family:
        # The current run_status is deliberately still "initializing" until
        # the verdict is known.  Use the freshly established local/rerun facts
        # for this one record while retaining manifest verification.
        family[current_key]["status"] = {
            "all_case_local_checks_passed": bool(current_local_pass),
            "deterministic_same_prefix_rerun": {"passed": bool(current_rerun_pass)},
        }
    required_keys = {
        "baseline": (12, round(baseline_dt, 15)),
        "time_refinement": (12, round(baseline_dt / 2.0, 15)),
        "shell_refinement": (16, round(baseline_dt, 15)),
    }
    missing = [name for name, key in required_keys.items() if key not in family]
    invalid = [
        name
        for name, key in required_keys.items()
        if key in family
        and (
            family[key].get("all_hashes_match") is not True
            or family[key].get("status", {}).get("all_case_local_checks_passed") is not True
            or family[key].get("status", {}).get("deterministic_same_prefix_rerun", {}).get("passed") is not True
        )
    ]
    if missing or invalid:
        return {
            "case_role": role,
            "required_family": {name: {"N_shell": key[0], "dt": key[1]} for name, key in required_keys.items()},
            "missing_cases": missing,
            "invalid_or_rerun_pending_cases": invalid,
            "time_step_status": "PENDING",
            "shell_cutoff_status": "PENDING",
            "evidence_status": "PENDING",
            "all_required_controls_available": False,
            "all_required_controls_passed": False,
            "solver_evidence_gate_passed": False,
        }

    baseline = load_compact_response_case(family[required_keys["baseline"]])
    time_case = load_compact_response_case(family[required_keys["time_refinement"]])
    shell_case = load_compact_response_case(family[required_keys["shell_refinement"]])
    time_comparison = signed_response_distance(baseline, time_case)
    shell_comparison = signed_response_distance(baseline, shell_case)
    time_pass = bool(
        time_comparison["signed_measure_distance"] <= EXTERNAL_RESPONSE_ABS_TOL
        or time_comparison["relative_signed_measure_distance"] <= EXTERNAL_RESPONSE_REL_TOL
    )
    shell_pass = bool(
        shell_comparison["signed_measure_distance"] <= EXTERNAL_RESPONSE_ABS_TOL
        or shell_comparison["relative_signed_measure_distance"] <= EXTERNAL_RESPONSE_REL_TOL
    )
    signal = time_comparison["left_response_norm"]
    solve_error = (
        maximum_branch_residual * max(signal, INSERTION_CONVERGENCE_ABS_TOL)
        + config.t_final * maximum_source_trace_residual
        + benchmark_error
    )
    combined = (
        local_insertion_error
        + time_comparison["signed_measure_distance"]
        + shell_comparison["signed_measure_distance"]
        + solve_error
    )
    ratio = signal / max(combined, np.finfo(float).tiny)
    resolved_nonzero = ratio >= EVIDENCE_FACTOR
    consistent_with_zero = ratio <= 1.0
    evidence_resolved = bool(resolved_nonzero or consistent_with_zero)
    if resolved_nonzero:
        response_classification = "RESOLVED_NONZERO_PROVISIONAL_TASK08"
        evidence_status = "PASS_RESOLVED_NONZERO"
    elif consistent_with_zero:
        response_classification = "CONSISTENT_WITH_ZERO_WITHIN_COMBINED_UNCERTAINTY"
        evidence_status = "PASS_ZERO_COMPATIBLE"
    else:
        response_classification = "UNRESOLVED_BETWEEN_ONE_AND_FIVE_TIMES_UNCERTAINTY"
        evidence_status = "PENDING_REFINEMENT"
    return {
        "case_role": role,
        "required_family": {name: {"N_shell": key[0], "dt": key[1]} for name, key in required_keys.items()},
        "missing_cases": [],
        "invalid_or_rerun_pending_cases": [],
        "time_step_comparison": time_comparison,
        "shell_cutoff_comparison": shell_comparison,
        "external_response_absolute_tolerance": EXTERNAL_RESPONSE_ABS_TOL,
        "external_response_relative_tolerance": EXTERNAL_RESPONSE_REL_TOL,
        "time_step_status": "PASS" if time_pass else "FAIL",
        "shell_cutoff_status": "PASS" if shell_pass else "FAIL",
        "evidence_budget": {
            "signal_complete_response_norm": signal,
            "insertion_error": local_insertion_error,
            "time_step_error": time_comparison["signed_measure_distance"],
            "shell_error": shell_comparison["signed_measure_distance"],
            "solve_source_and_benchmark_error": solve_error,
            "combined_error": combined,
            "signal_to_error": ratio,
            "required_factor_for_nonzero_claim": EVIDENCE_FACTOR,
            "zero_compatibility_threshold": 1.0,
        },
        "response_classification": response_classification,
        "evidence_status": evidence_status,
        "all_required_controls_available": True,
        "all_required_controls_passed": bool(time_pass and shell_pass),
        "solver_evidence_gate_passed": evidence_resolved,
        "nonzero_claim_supported": bool(resolved_nonzero),
        "zero_compatible": bool(consistent_with_zero),
    }

